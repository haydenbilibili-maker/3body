/**
 * 人物志 · 对话室：与人物在某一个具体的时刻相遇。
 *
 * 每位人物有一到两个场景（时刻）。场景决定：人物在哪里、此刻知道什么（之后的事他不知道）、
 * 由他先开口的那一句、适合问的问题，以及他心里藏着、要靠对话慢慢打开的那件事（secret + keys）。
 * 场景描写与台词均为本项目的创作，不是原著原文。
 * 后端按 scene 组织人设提示词（backend/routers/chat.py）；没有后端时，用 offline 里的台词与档案问答兜底。
 */

export interface FigureScene {
  id: string
  figure: string
  /** 场景名：地点 */
  title: string
  era: string
  /** 两三句场景描写 */
  setting: string
  /** 人物此刻知道什么：之后的事他不知道 */
  knows: string
  mood: string
  /** 人物先开口的那一句（含动作，动作写在全角括号里） */
  opening: string
  questions: string[]
  /** 心里藏着的那件事：心防打开之后，人物才会说出来 */
  secret: string
  /** 能慢慢打开心防的话题；每碰到一个，心防松一格 */
  keys: { word: string; hint: string; match: string[] }[]
  /** 没有后端时的兜底台词 */
  offline: string[]
}

