export function scenesOf(figure: string): FigureScene[] {
  return FIGURE_SCENES.filter((s) => s.figure === figure)
}

export function sceneById(id: string): FigureScene | undefined {
  return FIGURE_SCENES.find((s) => s.id === id)
}

/** 把人物的回答拆成台词与动作：全角括号里的是动作 */
export function splitStage(text: string): { kind: 'line' | 'stage'; text: string }[] {
  const out: { kind: 'line' | 'stage'; text: string }[] = []
  const re = /（[^（）]*）/g
  let last = 0
  for (let m = re.exec(text); m; m = re.exec(text)) {
    if (m.index > last) out.push({ kind: 'line', text: text.slice(last, m.index) })
    out.push({ kind: 'stage', text: m[0].slice(1, -1) })
    last = m.index + m[0].length
  }
  if (last < text.length) out.push({ kind: 'line', text: text.slice(last) })
  return out.filter((p) => p.text.trim())
}

/** 心防：对话里碰到了哪几个话题 */
export function touchedKeys(scene: FigureScene, userLines: string[]): Set<string> {
  const all = userLines.join('\n')
  return new Set(scene.keys.filter((k) => k.match.some((m) => all.includes(m))).map((k) => k.word))
}
